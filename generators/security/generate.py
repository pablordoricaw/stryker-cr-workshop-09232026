def _severity_for(score: Decimal) -> str:
    """CVSS base score → qualitative severity band (CVSS v3.1 ranges)."""
    if score >= Decimal("9.0"):
        return "Critical"
    if score >= Decimal("7.0"):
        return "High"
    if score >= Decimal("4.0"):
        return "Medium"
    return "Low"


def _sla_for(severity: str) -> int:
    """Remediation SLA (days) by severity — the workshop's fixed policy."""
    return {"Critical": 7, "High": 30, "Medium": 90, "Low": 180}[severity]


def build_cve_catalog() -> dict[str, dict[str, Any]]:
    """The full CVE catalog: the five documented CVEs plus synthesized extras.

    Every finding references a ``cve_id`` from this catalog, so a CVE's category,
    CVSS, severity, and exploit flag are consistent across all its findings (a
    CVSS base score is a per-CVE property, not a per-finding one).
    """
    catalog: dict[str, dict[str, Any]] = {}
    for (
        cve_id,
        title,
        category,
        cvss,
        vector,
        severity,
        exploit,
        _products,
        _remediation,
        _refs,
    ) in DOCUMENTED_CVES:
        catalog[cve_id] = {
            "cve_id": cve_id,
            "title": title,
            "category": category,
            "cvss_score": cvss,
            "cvss_vector": vector,
            "severity": severity,
            "exploit_available": exploit,
            "documented": True,
        }

    rng = random.Random(SEED + 7_000)
    # A spread of CVSS bases so severity bands are all represented.
    cvss_pool = [
        Decimal(value)
        for value in (
            "9.8", "9.1", "8.8", "8.2", "7.5", "7.1", "6.8", "6.5",
            "5.9", "5.3", "4.7", "4.3", "3.7", "3.1",
        )
    ]
    for index in range(45):
        year = 2025 if index % 3 == 0 else 2026
        cve_id = f"CVE-{year}-{40000 + index * 137}"
        category = VULN_CATEGORIES[index % len(VULN_CATEGORIES)]
        cvss = cvss_pool[index % len(cvss_pool)]
        product = _PRODUCT_TOKENS[index % len(_PRODUCT_TOKENS)]
        title = f"{category} in {product}"
        catalog[cve_id] = {
            "cve_id": cve_id,
            "title": title,
            "category": category,
            "cvss_score": cvss,
            "cvss_vector": "CVSS:3.1/AV:N/AC:L/PR:L/UI:N/S:U/C:L/I:L/A:L",
            "severity": _severity_for(cvss),
            "exploit_available": rng.random() < 0.3,
            "documented": False,
        }
    return catalog


def weighted_choice(rng: random.Random, values: Iterable[tuple[Any, int]]) -> Any:
    choices = list(values)
    return rng.choices(
        [value for value, _ in choices], weights=[weight for _, weight in choices], k=1
    )[0]


def dollars(value: Decimal) -> str:
    return f"${value:,.2f}"


def wrap(text: str, width: int) -> list[str]:
    words = text.split()
    lines: list[str] = []
    current: list[str] = []
    for word in words:
        if len(" ".join(current + [word])) > width and current:
            lines.append(" ".join(current))
            current = [word]
        else:
            current.append(word)
    if current:
        lines.append(" ".join(current))
    return lines


class SecurityPdf:
    """Deterministic canvas helper with deliberately varied layouts.

    A structural twin of the Finance generator's ``FinancePdf`` (same invariant
    reportlab settings, so bytes are reproducible) with a security-styled header.
    """

    def __init__(self, path: Path, title: str, accent: colors.Color, variant: int):
        path.parent.mkdir(parents=True, exist_ok=True)
        self.pdf = canvas.Canvas(
            str(path),
            pagesize=letter,
            pageCompression=1,
            invariant=1,
            pdfVersion=(1, 4),
        )
        self.title = title
        self.accent = accent
        self.variant = variant
        self.page = 0
        self.pdf.setTitle(title)
        self.pdf.setAuthor("Synthetic Stryker Databricks Workshop")
        self.new_page()

    def new_page(self) -> None:
        if self.page:
            self.footer()
            self.pdf.showPage()
        self.page += 1
        if self.variant % 2:
            self.pdf.setFillColor(self.accent)
            self.pdf.rect(0, 738, 612, 54, fill=1, stroke=0)
            self.pdf.setFillColor(colors.white)
            self.pdf.setFont("Helvetica-Bold", 16)
            self.pdf.drawString(36, 758, self.title[:66])
        else:
            self.pdf.setFillColor(colors.black)
            self.pdf.setFont("Helvetica-Bold", 17)
            self.pdf.drawString(42, 757, self.title[:64])
            self.pdf.setStrokeColor(self.accent)
            self.pdf.setLineWidth(3)
            self.pdf.line(42, 744, 570, 744)
        self.y = 714

    def footer(self) -> None:
        self.pdf.setFillColor(colors.HexColor("#5B6573"))
        self.pdf.setFont("Helvetica", 7)
        self.pdf.drawString(
            40, 24, "Synthetic workshop document — no real company or system data"
        )
        self.pdf.drawRightString(570, 24, f"Page {self.page}")

    def heading(self, text: str) -> None:
        self.pdf.setFillColor(self.accent)
        self.pdf.setFont("Helvetica-Bold", 11)
        self.pdf.drawString(42, self.y, text.upper())
        self.y -= 18

    def text(
        self, text: str, *, size: int = 9, indent: int = 0, leading: int = 12
    ) -> None:
        self.pdf.setFillColor(colors.HexColor("#20252B"))
        self.pdf.setFont("Helvetica", size)
        for line in wrap(text, max(38, int((510 - indent) / (size * 0.52)))):
            if self.y < 54:
                self.new_page()
            self.pdf.drawString(42 + indent, self.y, line)
            self.y -= leading
        self.y -= 3

    def kv(self, pairs: list[tuple[str, str]], columns: int = 2) -> None:
        col_width = 258 if columns == 2 else 172
        row_height = 30
        for start in range(0, len(pairs), columns):
            if self.y < 70:
                self.new_page()
            row = pairs[start : start + columns]
            for col, (label, value) in enumerate(row):
                x = 42 + col * col_width
                self.pdf.setFillColor(colors.HexColor("#667085"))
                self.pdf.setFont("Helvetica-Bold", 7)
                self.pdf.drawString(x, self.y, label.upper())
                self.pdf.setFillColor(colors.black)
                self.pdf.setFont("Helvetica", 9)
                self.pdf.drawString(x, self.y - 13, value[:44])
            self.y -= row_height
        self.y -= 4

    def table(
        self, headers: list[str], rows: list[list[str]], widths: list[int]
    ) -> None:
        font_size = 7
        height = 22
        x0 = 42
        if self.y < 100:
            self.new_page()
        self.pdf.setFillColor(self.accent)
        self.pdf.rect(x0, self.y - 15, sum(widths), 20, fill=1, stroke=0)
        self.pdf.setFillColor(colors.white)
        self.pdf.setFont("Helvetica-Bold", font_size)
        x = x0
        for header, width in zip(headers, widths):
            self.pdf.drawString(x + 3, self.y - 8, header[: int(width / 4.3)])
            x += width
        self.y -= 19
        for row_no, row in enumerate(rows):
            if self.y < 58:
                self.new_page()
            if row_no % 2 == 0:
                self.pdf.setFillColor(colors.HexColor("#F2F4F7"))
                self.pdf.rect(x0, self.y - 16, sum(widths), height, fill=1, stroke=0)
            self.pdf.setFillColor(colors.black)
            self.pdf.setFont("Helvetica", font_size)
            x = x0
            for value, width in zip(row, widths):
                max_chars = max(5, int(width / 4.0))
                display = (
                    value
                    if stringWidth(value, "Helvetica", font_size) < width - 6
                    else value[: max_chars - 1] + "…"
                )
                self.pdf.drawString(x + 3, self.y - 9, display)
                x += width
            self.y -= height
        self.y -= 8

    def finish(self) -> None:
        self.footer()
        self.pdf.save()


