def generate_findings() -> list[dict[str, Any]]:
    rng = random.Random(SEED + 50_000)
    catalog = build_cve_catalog()
    cve_ids = list(catalog)
    # Weight the documented CVEs high so they always appear in the findings (the
    # gold document-enrichment join must be non-empty), and give the rest a long
    # tail. Documented CVEs get weight 40; others a smaller deterministic weight.
    cve_weighted = [
        (cve_id, 40 if catalog[cve_id]["documented"] else 3 + (i % 5))
        for i, cve_id in enumerate(cve_ids)
    ]
    asset_weighted = [(asset, asset[-1]) for asset in ASSETS]
    rows: list[dict[str, Any]] = []
    start = date(2025, 10, 1)
    scan_counter: dict[tuple[str, str], str] = {}
    for i in range(ROW_COUNT):
        asset = weighted_choice(rng, asset_weighted)
        cve_id = weighted_choice(rng, cve_weighted)
        cve = catalog[cve_id]
        day_offset = int(rng.triangular(0, 350, 250))
        scan_date = start + timedelta(days=day_offset)

        # One scan run groups many findings for an asset on a date; reuse the
        # same scan_id for the same (asset, date) so scan_count is meaningful.
        scan_key = (asset[0], scan_date.isoformat())
        if scan_key not in scan_counter:
            scan_counter[scan_key] = f"SCN-{scan_date.strftime('%Y%m%d')}-{len(scan_counter) + 1:04d}"
        scan_id = scan_counter[scan_key]

        cvss = cve["cvss_score"]
        severity = cve["severity"]
        category = cve["category"]

        # Status mix. Production during a Q1-2026 remediation backlog skews Open —
        # a traceable "production critical backlog" story for later exercises.
        in_backlog = asset[3] == "Production" and date(2026, 1, 15) <= scan_date <= date(2026, 3, 31)
        if in_backlog:
            status = rng.choices(
                ["Open", "In Remediation", "Resolved", "Accepted Risk"],
                weights=[58, 26, 12, 4], k=1,
            )[0]
        else:
            status = rng.choices(
                ["Open", "In Remediation", "Resolved", "Accepted Risk"],
                weights=[34, 24, 36, 6], k=1,
            )[0]

        age_days = int(rng.triangular(0, 210, 40))
        first_detected = scan_date - timedelta(days=age_days)

        base_hours = CATEGORY_BASE_HOURS[category]
        severity_factor = {
            "Critical": Decimal("1.6"),
            "High": Decimal("1.3"),
            "Medium": Decimal("1.0"),
            "Low": Decimal("0.7"),
        }[severity]
        jitter = Decimal(str(rng.choice([0.9, 0.95, 1.0, 1.05, 1.1])))
        remediation_hours = (base_hours * severity_factor * jitter).quantize(MONEY)

        weight = Decimal(asset[-1])
        weighted_risk = (cvss * weight).quantize(MONEY)
        asset_value_at_risk = (
            asset[7] * (cvss / Decimal(10)) * Decimal(str(rng.choice([0.85, 0.9, 1.0, 1.1])))
        ).quantize(MONEY, rounding=ROUND_HALF_UP)

        detected = datetime.combine(
            scan_date, datetime.min.time(), tzinfo=timezone.utc
        ) + timedelta(hours=6, minutes=i % 53)
        updated = detected + timedelta(days=rng.choice([0, 0, 1, 2]), hours=2)

        row = {
            "finding_id": f"FND-{i + 1:06d}",
            "scan_id": scan_id,
            "scan_date": scan_date,
            "detected_timestamp": detected,
            "asset_id": asset[0],
            "asset_name": asset[1],
            "asset_type": asset[2],
            "environment": asset[3],
            "business_unit": asset[4],
            "owner_team": asset[5],
            "cve_id": cve_id,
            "vulnerability_title": cve["title"],
            "vulnerability_category": category,
            "severity": severity,
            "cvss_score": cvss,
            "cvss_vector": cve["cvss_vector"],
            "status": status,
            "first_detected_date": first_detected,
            "age_days": age_days,
            "remediation_hours": remediation_hours,
            "asset_value_at_risk": asset_value_at_risk,
            "weighted_risk": weighted_risk,
            "remediation_sla_days": _sla_for(severity),
            "exploit_available": bool(cve["exploit_available"]),
            "detection_source": rng.choices(
                list(SCANNERS) + ["Manual Pentest"],
                weights=[26, 22, 20, 14, 12, 6], k=1,
            )[0],
            "source_updated_at": updated,
        }
        rows.append(row)
    return rows


def csv_value(value: Any) -> Any:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (date, datetime)):
        return value.isoformat()
    if isinstance(value, Decimal):
        return format(value, "f")
    return value


